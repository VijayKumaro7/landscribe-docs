/**
 * Renders the "PR Branch Flow" entry for a pull request and publishes it.
 *
 * Driven by .github/workflows/pr-branch-flow.yml, which runs on every PR event.
 * All PR metadata (number, title, author, head/base branch, state, repository)
 * comes straight from the `pull_request` webhook payload at GITHUB_EVENT_PATH,
 * so no extra API reads are needed and the output always matches the PR.
 *
 * Commands:
 *   entry    Write docs/pr-flow/pr-<number>.md (one file per PR, so entries
 *            never overwrite each other and an update never duplicates).
 *            Sets `changed=true|false` in GITHUB_OUTPUT.
 *   comment  Create or update a single sticky comment on the PR.
 *
 * Usage:
 *   node scripts/pr-branch-flow.mjs entry   [--out <dir>] [--event <file>]
 *   node scripts/pr-branch-flow.mjs comment [--event <file>]
 *
 * `comment` needs GITHUB_TOKEN. PR titles and branch names are untrusted input:
 * every value is sanitised before it reaches Markdown or Mermaid.
 */

import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const COMMENT_MARKER = "<!-- pr-branch-flow:comment -->";
const ENTRY_MARKER = (n) => `<!-- pr-branch-flow:entry pr=${n} — generated by scripts/pr-branch-flow.mjs, do not edit by hand -->`;

// ---- sanitising ---------------------------------------------------------
const oneLine = (s) => String(s ?? "").replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, " ").replace(/\s+/g, " ").trim();
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);

/** Plain text safe inside a Markdown table cell or heading. */
export const mdText = (s) =>
  oneLine(s)
    .replace(/&/g, "&amp;")
    .replace(/[\\`*_{}[\]<>()#+!|~]/g, "\\$&");

/** Inline code span; backticks cannot be escaped inside one, so they are swapped out. */
export const mdCode = (s, inTable = false) => {
  const v = oneLine(s).replace(/`/g, "'");
  return "`" + (inTable ? v.replace(/\|/g, "\\|") : v) + "`";
};

/** Text for a quoted Mermaid label. */
const mmdLabel = (s, max) =>
  clip(oneLine(s).replace(/"/g, "'").replace(/[`<>[\]{}()|;#&\\]/g, " ").replace(/\s+/g, " ").trim(), max);

// ---- model --------------------------------------------------------------
const KINDS = [
  ["feature", /^(feature|feat)\//i],
  ["bugfix", /^(bugfix|fix)\//i],
  ["hotfix", /^hotfix\//i],
  ["release", /^release\//i],
  ["develop", /^(develop|dev|development)$/i],
  ["main", /^(main|master|trunk)$/i],
];
export const branchKind = (name) => KINDS.find(([, re]) => re.test(name))?.[0] ?? "other";

export function normalizePr(pr, event = {}) {
  const number = Number(pr?.number);
  if (!Number.isInteger(number) || number < 1) throw new Error(`Invalid PR number: ${pr?.number}`);
  const repository = pr.base?.repo?.full_name ?? event.repository?.full_name ?? "unknown/unknown";
  const headRepo = pr.head?.repo ?? null;
  const merged = Boolean(pr.merged || pr.merged_at);
  const status = merged ? "Merged" : pr.state === "closed" ? "Closed" : "Open";
  const url = typeof pr.html_url === "string" && /^https:\/\/[^\s"'<>]+$/.test(pr.html_url) ? pr.html_url : null;
  return {
    number,
    title: oneLine(pr.title) || "(untitled)",
    repository,
    author: oneLine(pr.user?.login) || "(unknown)",
    status,
    draft: Boolean(pr.draft) && status === "Open",
    source: oneLine(pr.head?.ref) || "(unknown)",
    target: oneLine(pr.base?.ref) || "(unknown)",
    // null head repo means the fork was deleted; the ref name is still reported by GitHub.
    sourceRepo: headRepo ? headRepo.full_name : null,
    fork: headRepo ? headRepo.full_name !== repository : false,
    created: pr.created_at ? String(pr.created_at).slice(0, 10) : null,
    merged: pr.merged_at ? String(pr.merged_at).slice(0, 10) : null,
    url,
  };
}

export function prFromEvent(event) {
  if (!event?.pull_request) throw new Error("Event payload has no pull_request");
  return normalizePr(event.pull_request, event);
}

// ---- rendering ----------------------------------------------------------
export function renderBody(p, headingLevel = 4) {
  const h = "#".repeat(headingLevel);
  const statusText = p.status + (p.draft ? " (draft)" : "");
  const rows = [
    ["Repository", mdText(p.repository)],
    ["Author", mdText(p.author)],
    ["Status", statusText],
    ["Source Branch", `${mdCode(p.source, true)} (${branchKind(p.source)})`],
    ["Target Branch", `${mdCode(p.target, true)} (${branchKind(p.target)})`],
  ];
  if (p.fork) rows.push(["Source Repository", `${mdText(p.sourceRepo)} (fork)`]);
  if (!p.fork && p.sourceRepo === null) rows.push(["Source Repository", "no longer available (deleted fork)"]);
  if (p.created) rows.push(["Created", p.created]);
  if (p.merged) rows.push(["Merged", p.merged]);
  if (p.url) rows.push(["PR Link", `[#${p.number}](${p.url})`]);

  const cls = p.status.toLowerCase();
  const mermaid = [
    "flowchart LR",
    `    src(["${mmdLabel(p.source, 60)}"]):::source --> pr["#${p.number} ${mmdLabel(p.title, 40)}"]:::${cls} --> dst[["${mmdLabel(p.target, 60)}"]]:::target`,
    ...(p.url ? [`    click pr "${p.url}" "PR #${p.number}" _blank`] : []),
    "    classDef source fill:#dbeafe,stroke:#1d4ed8,color:#1e3a8a",
    "    classDef target fill:#fef3c7,stroke:#b45309,stroke-width:3px,color:#78350f",
    "    classDef merged fill:#ede9fe,stroke:#6d28d9,color:#4c1d95",
    "    classDef open fill:#dcfce7,stroke:#15803d,color:#14532d",
    "    classDef closed fill:#fee2e2,stroke:#b91c1c,stroke-dasharray:4 3,color:#7f1d1d",
  ].join("\n");

  return [
    `${h} PR #${p.number}: ${mdText(p.title)}`,
    "",
    "| Attribute | Details |",
    "|---|---|",
    ...rows.map(([k, v]) => `| ${k} | ${v} |`),
    "",
    "**PR Branch Flow:**",
    "",
    `${mdCode(p.source)} → ${mdCode(p.target)}`,
    "",
    "```mermaid",
    mermaid,
    "```",
    "",
    "_Source → PR → target. Blue: source branch, amber: target branch; PR colour shows status (green open, purple merged, red closed)._",
  ].join("\n");
}

export const renderEntry = (p) =>
  [
    ENTRY_MARKER(p.number),
    renderBody(p, 4),
    "",
    "_Status is as of the last time this entry was generated; the pull request itself is authoritative._",
    "",
  ].join("\n");

export const renderComment = (p) => [COMMENT_MARKER, renderBody(p, 3), ""].join("\n");

export const entryPath = (dir, number) => path.join(dir, `pr-${number}.md`);

// ---- commands -----------------------------------------------------------
export function writeEntry(p, dir) {
  const file = entryPath(dir, p.number);
  const next = renderEntry(p);
  const prev = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (prev === next) return { file, changed: false };
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, next);
  return { file, changed: true };
}

async function upsertComment(p, event) {
  const token = process.env.GITHUB_TOKEN;
  if (!token) throw new Error("GITHUB_TOKEN is not set");
  const api = process.env.GITHUB_API_URL || "https://api.github.com";
  const base = `${api}/repos/${p.repository}/issues/${p.number}/comments`;
  const headers = { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28" };
  const body = renderComment(p);

  // Only trust a marker comment written by the Actions bot, so a user cannot hijack the slot.
  let existing = null;
  for (let page = 1; !existing; page++) {
    const res = await fetch(`${base}?per_page=100&page=${page}`, { headers });
    if (!res.ok) throw new Error(`List comments failed: ${res.status}`);
    const batch = await res.json();
    existing = batch.find((c) => c.user?.login === "github-actions[bot]" && c.body?.includes(COMMENT_MARKER)) ?? null;
    if (batch.length < 100) break;
  }
  if (existing?.body === body) return "unchanged";
  const res = existing
    ? await fetch(`${api}/repos/${p.repository}/issues/comments/${existing.id}`, { method: "PATCH", headers, body: JSON.stringify({ body }) })
    : await fetch(base, { method: "POST", headers, body: JSON.stringify({ body }) });
  if (!res.ok) throw new Error(`${existing ? "Update" : "Create"} comment failed: ${res.status}`);
  return existing ? "updated" : "created";
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const opt = (name, fallback) => (rest.includes(name) ? rest[rest.indexOf(name) + 1] : fallback);
  const eventFile = opt("--event", process.env.GITHUB_EVENT_PATH);
  if (!eventFile) throw new Error("No event payload: set GITHUB_EVENT_PATH or pass --event");
  const event = JSON.parse(readFileSync(eventFile, "utf8"));
  const pr = prFromEvent(event);

  if (cmd === "entry") {
    const { file, changed } = writeEntry(pr, path.resolve(opt("--out", path.join(root, "docs/pr-flow"))));
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `changed=${changed}\n`);
    console.log(`${changed ? "Wrote" : "Unchanged"}: ${file}`);
  } else if (cmd === "comment") {
    try {
      console.log(`Comment ${await upsertComment(pr, event)} on #${pr.number}`);
    } catch (err) {
      // Fork PRs get a read-only token; that must not fail the PR's checks.
      console.log(`::warning::Could not publish PR branch flow comment: ${err.message}`);
    }
  } else {
    throw new Error("Usage: pr-branch-flow.mjs <entry|comment> [--out dir] [--event file]");
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
